"""Writes runtime/game_addrs.inc: every address in tools/game_addrs.txt for each release.

  python tools/game_addrs.py

Each entry names an ELF symbol (looked up in files/tsc_wii_release_dvd.elf) or gives a hex
address. A func must be a function symbol, a data entry an object symbol. A release whose
inputs are not here keeps its column from the existing file.
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from elf import Elf                  # noqa: E402
from regions import REGIONS, ROOT    # noqa: E402

SRC = os.path.join(ROOT, 'tools', 'game_addrs.txt')
OUT = os.path.join(ROOT, 'runtime', 'game_addrs.inc')
KINDS = {'func': 'FUNC', 'code': 'CODE', 'data': 'DATA'}


def read_list():
    """[(name, kind, symbol-or-address, description)]"""
    rows = []
    for ln in open(SRC, encoding='utf-8'):
        ln = ln.split('#', 1)[0].strip()
        if not ln:
            continue
        parts = ln.split(None, 3)
        if parts[1] not in KINDS:
            sys.exit(f'{parts[0]}: unknown kind {parts[1]}')
        rows.append((parts[0], parts[1], parts[2], parts[3] if len(parts) > 3 else ''))
    return rows


def load_inc():
    """runtime/game_addrs.inc as [(name, kind, {game ID: address})], in file order."""
    rows = []
    if os.path.exists(OUT):
        for m in re.finditer(r'GAME_ADDR\((\w+),\s*(\w+)((?:,\s*0x[0-9A-F]+)+)\)', open(OUT).read()):
            vals = [int(x, 16) for x in m.group(3).replace(',', ' ').split()]
            rows.append((m.group(1), m.group(2).lower(), {r.game_id: v for r, v in zip(REGIONS, vals)}))
    return rows


def resolve(region, rows):
    syms = Elf(region.elf()).by_name()
    out, errors = {}, []
    for name, kind, ref, _ in rows:
        if re.fullmatch(r'[0-9A-Fa-f]{8}', ref):
            out[name] = int(ref, 16)
            continue
        s = syms.get(ref)
        if s is None:
            errors.append(f'{name}: no unique symbol {ref}')
        elif (kind == 'func') != (s.kind == 'func') or kind == 'code':
            errors.append(f'{name}: {ref} is a {s.kind}, not {kind}')
        else:
            out[name] = s.addr
    return out, errors


def main():
    rows = read_list()
    prev = {name: cols for name, _, cols in load_inc()}
    cols, errors = {}, []
    for r in REGIONS:
        if r.data_dir():
            cols[r.game_id], err = resolve(r, rows)
            errors += [f'{r.game_id} {e}' for e in err]
        else:
            print(f'{r.game_id}: inputs not here, keeping the previous addresses')
            cols[r.game_id] = {name: prev.get(name, {}).get(r.game_id, 0) for name, *_ in rows}
    if errors:
        sys.exit('\n'.join(errors))

    w = max(len(n) for n, *_ in rows)
    lines = [
        '// Generated by tools/game_addrs.py from tools/game_addrs.txt: the game addresses the',
        '// runtime and the recompiler use, one column per release. Do not edit.',
        '//',
        f'//        {"name,".ljust(w + 1)} kind, ' + ' '.join((r.game_id + ',').ljust(11) for r in REGIONS).rstrip(' ,'),
    ]
    for name, kind, _, desc in rows:
        vals = ', '.join(f'0x{cols[r.game_id][name]:08X}' for r in REGIONS)
        lines.append(f'GAME_ADDR({(name + ",").ljust(w + 1)} {KINDS[kind]}, {vals})' + (f'   // {desc}' if desc else ''))
    text = '\n'.join(lines) + '\n'
    old = open(OUT, newline='\n').read() if os.path.exists(OUT) else None
    if old != text:
        with open(OUT, 'w', newline='\n') as fp:
            fp.write(text)
        print(f'wrote {OUT}')
    else:
        print('runtime/game_addrs.inc is up to date')


if __name__ == '__main__':
    main()
